"""Build the Fractus-II website page (index.html) and PDF from fractus-ii.md.

Usage: python3 build/build.py [web|pdf|all]
Requires pandoc (3.x) and tectonic on PATH.
"""
import pathlib, re, subprocess, sys, tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "fractus-ii.md"
META = {
    "title": "Fractus-II",
    "subtitle": "One Shape, Folded at Every Depth",
    "author": "Ridley DiSiena",
    "date": "November 2026",
}
TAGLINE = ("A thought experiment on how a single folded geometry might give rise to "
           "forces, matter, spin, light, gravity, and the dark universe")
LICENSE_LINE = "Text licensed CC BY-NC 4.0."
SOURCE_LINE = "Source, website and citation: <https://ridleydisiena.github.io/fractus-ii/>"


def body_without_title(text):
    """Drop the title block (everything before the first horizontal rule)."""
    head, sep, rest = text.partition("\n---\n")
    if not sep:
        sys.exit("title block separator not found")
    return rest.lstrip("\n")


def web():
    html = subprocess.run(
        ["pandoc", str(SRC), "-f", "markdown", "-t", "html5", "--katex", "--wrap=none"],
        check=True, capture_output=True, text=True).stdout
    # On the web page the author/date lines give way to the audio player and byline.
    title_lines = "<p><strong>Ridley DiSiena</strong></p>\n<p><em>November 2026</em></p>\n"
    if title_lines not in html:
        sys.exit("author/date lines not found in title block")
    html = html.replace(title_lines, "{% endraw %}{% include listen.html %}{% raw %}\n", 1)
    front = ("---\nlayout: manuscript\ntitle: Fractus-II\npermalink: /\n---\n"
             "<!-- Generated by build/build.py from fractus-ii.md. Do not edit by hand. -->\n")
    (ROOT / "index.html").write_text(front + "{% raw %}\n" + html + "{% endraw %}\n", encoding="utf-8")
    print("wrote index.html")


def pdf():
    body = body_without_title(SRC.read_text(encoding="utf-8"))
    with tempfile.TemporaryDirectory() as tmp:
        md = pathlib.Path(tmp) / "body.md"
        md.write_text("\\clearpage\n\n" + body, encoding="utf-8")
        meta = pathlib.Path(tmp) / "meta.yaml"
        lines = [f"{k}: \"{v}\"" for k, v in META.items()]
        lines += ["abstract: |", "  \\centering", "", f"  *{TAGLINE}.*", "", "  \\bigskip", "",
                  f"  {LICENSE_LINE}\\", f"  {SOURCE_LINE}"]
        meta.write_text("\n".join(lines) + "\n", encoding="utf-8")
        cmd = ["pandoc", str(md), "-f", "markdown", "-o", str(ROOT / "fractus-ii.pdf"),
               "--pdf-engine=tectonic", "--toc", "--toc-depth=2",
               "-H", str(ROOT / "build" / "header.tex"),
               "-V", "documentclass=article", "-V", "papersize=letter", "-V", "fontsize=11pt",
               "-V", "geometry:margin=1.1in", "-V", "colorlinks=true",
               "-V", "linkcolor=violet", "-V", "urlcolor=violet", "-V", "toccolor=black",
               "-V", "mainfont=texgyrepagella",
               "-V", "mainfontoptions=Extension=.otf,UprightFont=*-regular,BoldFont=*-bold,ItalicFont=*-italic,BoldItalicFont=*-bolditalic",
               "-V", "mathfont=texgyrepagella-math.otf",
               "--metadata-file", str(meta)]
        subprocess.run(cmd, check=True, cwd=tmp)
    print("wrote fractus-ii.pdf")


if __name__ == "__main__":
    what = sys.argv[1] if len(sys.argv) > 1 else "all"
    if what in ("web", "all"):
        web()
    if what in ("pdf", "all"):
        pdf()
